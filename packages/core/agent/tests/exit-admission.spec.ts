import { describe, expect, it, vi } from 'vitest'
import { ExitAdmission } from '../src/exit-admission.ts'

describe('silent exit admission', () => {
  const ready = () => {
    const gate = new ExitAdmission()
    gate.registerRequired('agents', () => 'idle')
    gate.registerRequired('jobs', () => 'idle')
    gate.registerRequired('schedule', () => 'idle')
    return gate
  }
  it('refuses missing, failed and uncertain providers', () => {
    const gate = new ExitAdmission()
    expect(gate.tryReserve()).toEqual({ kind: 'unknown' })
    gate.registerRequired('agents', () => 'idle')
    gate.registerRequired('jobs', () => { throw new Error('unavailable') })
    gate.registerRequired('schedule', () => 'idle')
    expect(gate.tryReserve()).toEqual({ kind: 'unknown' })
  })
  it('blocks active work and asynchronous admissions', () => {
    const gate = ready()
    const release = gate.begin()
    expect(gate.tryReserve()).toEqual({ kind: 'busy' })
    release(); release()
    const remove = gate.registerOptional(() => 'busy')
    expect(gate.tryReserve()).toEqual({ kind: 'busy' })
    remove()
    const unknown = gate.registerOptional(() => 'unknown')
    expect(gate.tryReserve()).toEqual({ kind: 'unknown' })
    unknown()
    const reservation = gate.tryReserve()
    expect(reservation.kind).toBe('reserved')
    if (reservation.kind === 'reserved') gate.cancel(reservation.id)
  })
  it('invalidates a reservation when new work starts', () => {
    const gate = ready()
    const reservation = gate.tryReserve()
    if (reservation.kind !== 'reserved') throw new Error('expected reservation')
    const release = gate.begin()
    expect(gate.commit(reservation.id)).toBe(false)
    expect(gate.tryReserve()).toEqual({ kind: 'busy' })
    release()
    expect(gate.tryReserve().kind).toBe('reserved')
  })
  it('unfreezes canceled commits and finalizes only matching leases', () => {
    const gate = ready()
    const reservation = gate.tryReserve()
    if (reservation.kind !== 'reserved') throw new Error('expected reservation')
    expect(gate.commit(reservation.id)).toBe(true)
    expect(() => gate.begin()).toThrow('shutting down')
    gate.cancel(reservation.id)
    expect(() => gate.assertAdmission()).not.toThrow()
    const next = gate.tryReserve()
    if (next.kind !== 'reserved') throw new Error('expected reservation')
    gate.cancel(reservation.id)
    expect(gate.commit(next.id)).toBe(true)
    const shutdown = vi.fn()
    expect(gate.finalize(next.id, shutdown)).toBe(true)
    expect(shutdown).toHaveBeenCalledOnce()
    expect(() => gate.begin()).toThrow('shutting down')
  })
  it('unfreezes on expiry or synchronous failure', () => {
    vi.useFakeTimers()
    try {
      const gate = ready()
      const first = gate.tryReserve()
      if (first.kind !== 'reserved') throw new Error('expected reservation')
      expect(gate.commit(first.id)).toBe(true)
      vi.advanceTimersByTime(10_001)
      expect(() => gate.assertAdmission()).not.toThrow()
      const next = gate.tryReserve()
      if (next.kind !== 'reserved') throw new Error('expected reservation')
      expect(gate.commit(next.id)).toBe(true)
      expect(gate.finalize(next.id, () => { throw new Error('failed') })).toBe(false)
      expect(() => gate.assertAdmission()).not.toThrow()
    } finally { vi.useRealTimers() }
  })
  it('invalidates a reservation when a required provider unloads and resumes listeners after rollback', () => {
    const gate = new ExitAdmission()
    gate.registerRequired('agents', () => 'idle')
    const unload = gate.registerRequired('jobs', () => 'idle')
    gate.registerRequired('schedule', () => 'idle')
    const lease = gate.tryReserve()
    if (lease.kind !== 'reserved') throw new Error('expected reservation')
    unload()
    expect(gate.commit(lease.id)).toBe(false)
    expect(gate.tryReserve()).toEqual({ kind: 'unknown' })
    gate.registerRequired('jobs', () => 'idle')
    const next = gate.tryReserve()
    if (next.kind !== 'reserved') throw new Error('expected reservation')
    expect(gate.commit(next.id)).toBe(true)
    const resumed = vi.fn()
    const unsubscribe = gate.onReopen(resumed)
    gate.cancel(next.id)
    expect(resumed).toHaveBeenCalledOnce()
    unsubscribe()
  })
})
