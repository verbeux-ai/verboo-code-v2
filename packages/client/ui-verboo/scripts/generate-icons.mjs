/** Generate the shipped Lucide subset; fail when an upstream glyph has no deliberate replacement. */
import { readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
const require = createRequire(import.meta.url)
const data = require('@iconify-json/lucide/icons.json')
const root = new URL('../', import.meta.url)
const mapping = JSON.parse(await readFile(new URL('icon-map.json',root),'utf8'))
const upstream = await readFile(new URL('../ui-primitives/src/icons/artwork.ts',root),'utf8')
const names = [...upstream.matchAll(/^  '([^']+)':/gm)].map(m=>m[1])
for (const name of names) if (!mapping[name]) throw new Error(`Map the new upstream glyph: ${name}`)
const own = ['mail','calendar-days','kanban','figma','arrow-right','arrow-up-right','folder','folder-open','cable','credit-card','log-out','settings-2','panel-left-close','panel-left-open','plus','file-code-2','check','x','rotate-cw','loader-circle','external-link','sun','moon','monitor','search','circle-help','triangle-alert','fingerprint','layers','command','shield-check','circle-user-round','square-pen','chevron-right','git-branch','workflow','layout-grid']
const glyphs = {}
for (const name of new Set([...Object.values(mapping), ...own])) {
 let icon = data.icons[name]
 if (!icon && data.aliases?.[name]) icon=data.icons[data.aliases[name].parent]
 if (!icon) throw new Error(`Unknown Lucide icon: ${name}`)
 glyphs[name]=icon.body
}
await writeFile(new URL('src/client/icons.generated.ts',root), `// Generated by scripts/generate-icons.mjs. Lucide artwork: ISC license.\n/** Trusted Lucide SVG bodies shipped with the product. */\nexport const glyphs = ${JSON.stringify(glyphs,null,2).replace(/\n}/g, ',\n}')} as const\n/** Deliberate replacements for each upstream icon name. */\nexport const replacements = ${JSON.stringify(mapping,null,2).replace(/\n}/g, ',\n}')} as const\n`)
execFileSync(process.execPath, [
  fileURLToPath(new URL('../../../node_modules/oxlint/bin/oxlint', root)),
  '--fix',
  fileURLToPath(new URL('src/client/icons.generated.ts', root)),
], { cwd: fileURLToPath(new URL('../../../', root)), stdio: 'inherit' })
